def error_table() -> str:
    names = {t["id"]: t["name"] for t in RESULT["term_types"]}
    rows = []
    for r in VERIFY["rejected"]:
        q = r["quote"]
        q = tex(q) if len(q) <= 70 else tex(q[:67].rstrip()) + "\\ldots"
        rows.append(f"    {tex(names[r['term_type']])} & {SHORT[r['doc']]} & ``{q}'' & {CAUSE[(r['term_type'], r['where'])]} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\begin{tabularx}{\\textwidth}{@{}llXl@{}}",
        "    \\toprule", "    Term type & Cited source & Rejected quote & Diagnosis \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "\\end{tabularx}", ""])


def catalogue_table() -> str:
    tts = RESULT["term_types"]
    cells = [f"{tex(t['name'])} & {len(t['values'])} & {len(t['sources']['documents'])}" for t in tts]
    half = (len(cells) + 1) // 2
    left, right = cells[:half], cells[half:] + [" & & "] * (half - len(cells[half:]))
    rows = [f"    {l} & {r} \\\\" for l, r in zip(left, right)]
    hdr = "Term type & Vals & Docs"
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrr@{\\hspace{14pt}}lrr@{}}",
        "    \\toprule", f"    {hdr} & {hdr} \\\\", "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


def plot_data() -> None:
    tts = RESULT["term_types"]
    docs = collections.Counter(len(t["sources"]["documents"]) for t in tts)
    vals = collections.Counter(len(t["values"]) for t in tts)
    (TABLES / "docs_per_type.dat").write_text("n count\n" + "\n".join(f"{k} {docs[k]}" for k in range(1, max(docs) + 1)) + "\n")
    (TABLES / "values_per_type.dat").write_text("n count\n" + "\n".join(f"{k} {vals[k]}" for k in range(min(vals), max(vals) + 1)) + "\n")


