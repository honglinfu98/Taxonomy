def tex(s: str) -> str:
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
             .replace("$", "\\$").replace("#", "\\#").replace("_", "\\_").replace("—", "--")
             .replace("‘", "`").replace("’", "'").replace("“", "``").replace("”", "''"))


def case_table(tt_id: str = "asset_reference_type") -> str:
    tt = next(t for t in RESULT["term_types"] if t["id"] == tt_id)
    rows = []
    for v in tt["values"]:
        c = v["citations"][0]
        rows.append(f"    {tex(v['value'])} & {tex(v['definition'])} & {SHORT[c['doc']]} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\begin{tabularx}{\\columnwidth}{@{}>{\\raggedright\\arraybackslash}p{0.22\\columnwidth}Xl@{}}",
        "    \\toprule", "    Value & Definition (model output) & Cited source \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "\\end{tabularx}", ""])


CAUSE = {  # (term_type, where) -> diagnosis, from comparing each quote with its cited section
    ("smart_contract_definition_scope", "value:distributed ledger protocol"): "definition compressed",
    ("software_architecture", "value:monolithic"): "sentence tail rephrased",
    ("code_license_openness", "type"): "enumeration items elided",
    ("custodian_or_custody_model", "type"): "no overlap with cited section",
    ("decentralised_control_status_actor", "value:control via governance token (token holders)"): "sentence tail rephrased",
    ("aml_obligations_applicability", "value:money services business (US)"): "sentence tail rephrased",
    ("related_person_affiliation", "type"): "definition compressed",
    ("related_person_affiliation", "value:related person (founder or officer)"): "enumeration items elided",
    ("risk_type_illicit_finance", "type"): "no overlap with cited section",
    ("consensus_participant_validator_capacity", "type"): "definition compressed",
}


def error_table() -> str:
    names = {t["id"]: t["name"] for t in RESULT["term_types"]}
    rows = []
    for r in VERIFY["rejected"]:
        q = r["quote"]
        q = tex(q) if len(q) <= 70 else tex(q[:67].rstrip()) + "\\ldots"
        rows.append(f"    {tex(names[r['term_type']])} & {SHORT[r['doc']]} & ``{q}'' & {CAUSE[(r['term_type'], r['where'])]} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\begin{tabularx}{\\textwidth}{@{}llXl@{}}",
        "    \\toprule", "    Term type & Cited source & Rejected quote & Diagnosis \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "\\end{tabularx}", ""])


def catalogue_table() -> str:
    tts = RESULT["term_types"]
    cells = [f"{tex(t['name'])} & {len(t['values'])} & {len(t['sources']['documents'])}" for t in tts]
    half = (len(cells) + 1) // 2
    left, right = cells[:half], cells[half:] + [" & & "] * (half - len(cells[half:]))
    rows = [f"    {l} & {r} \\\\" for l, r in zip(left, right)]
    hdr = "Term type & Vals & Docs"
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{@{}lrr@{\\hspace{14pt}}lrr@{}}",
        "    \\toprule", f"    {hdr} & {hdr} \\\\", "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


def plot_data() -> None:
    tts = RESULT["term_types"]
    docs = collections.Counter(len(t["sources"]["documents"]) for t in tts)
    vals = collections.Counter(len(t["values"]) for t in tts)
    (TABLES / "docs_per_type.dat").write_text("n count\n" + "\n".join(f"{k} {docs[k]}" for k in range(1, max(docs) + 1)) + "\n")
    (TABLES / "values_per_type.dat").write_text("n count\n" + "\n".join(f"{k} {vals[k]}" for k in range(min(vals), max(vals) + 1)) + "\n")


if __name__ == "__main__":
    (TABLES / "case_reference_asset.tex").write_text(case_table())
    (TABLES / "errors.tex").write_text(error_table())
    (TABLES / "catalogue.tex").write_text(catalogue_table())
    plot_data()
    import sys
    sys.path.insert(0, str(ROOT))
    from taxonomy.establishment.prompts import TAXONOMIST_INSTRUCTIONS, TASK_A_PROMPT
    (TABLES / "prompt_system.txt").write_text(TAXONOMIST_INSTRUCTIONS)
    (TABLES / "prompt_task_a.txt").write_text(TASK_A_PROMPT)
    print("wrote case, error and catalogue tables, plot data and prompt listings")
