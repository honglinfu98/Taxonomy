"""Generate the Task A tables from output/establishment/term_types.json and the corpus.

    python paper/scripts/task_a_tables.py        (from the repo root)

Writes paper/tables/task_a_summary.tex (term types by category) and
paper/tables/corpus.tex (source documents, their size and how many term types
cite them). Re-run after any new Task A run so the paper never carries stale numbers.
"""
from __future__ import annotations

import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULT = json.loads((ROOT / "output" / "establishment" / "term_types.json").read_text())
VERIFY = json.loads((ROOT / "output" / "establishment" / "term_types.verification.json").read_text())
CORPUS = (ROOT / "context" / "taxonomy_corpus.txt").read_text()
TABLES = ROOT / "paper" / "tables"

DOC_RE = re.compile(r'<document index="(\d+)"([^>]*)>\n(.*?)\n</document>', re.S)
SEC_RE = re.compile(r'<section label="([^"]*)">\n(.*?)\n</section>', re.S)
CATS = [("asset", "Asset"), ("technology", "Technology"), ("actor", "Actor"),
        ("activity", "Activity"), ("obligation_or_risk", "Obligation or risk")]
SHORT = {  # doc index -> short name for the corpus table
    1: "Tasca \\& Tessone taxonomy", 2: "Zhang et al.\\ taxonomy", 3: "DLT-Corpus paper",
    4: "MiCA, Reg.\\ 2023/1114", 5: "AMLR, Reg.\\ 2024/1624", 6: "Transfer of Funds, Reg.\\ 2023/1113",
    7: "DORA, Reg.\\ 2022/2554", 8: "FSMA (Cryptoassets) Regs 2026", 9: "CARF Regs 2025",
    10: "CLARITY Act (Senate-reported)", 11: "CLARITY Act (House-passed)", 12: "FIT21, H.R.\\ 4763",
    13: "GENIUS Act, Pub.\\ L.\\ 119-27", 14: "Executive Order 14178", 15: "PWG Digital Asset Markets Report",
    16: "FinCEN CVC Guidance 2019", 17: "FATF VA/VASP Guidance 2021", 18: "FATF Targeted Update 2025",
    19: "FATF Targeted Update 2026", 20: "Basel SCO60", 21: "FSB Recommendations 2023",
    22: "IOSCO Recommendations 2023", 23: "UN Cybercrime Convention", 24: "Budapest Convention",
}
JUR = {"": "Acad.", "EU": "EU", "UK": "UK", "US": "US", "INTL": "Intl"}


def cites(tt: dict) -> list[dict]:
    return tt.get("citations", []) + [c for v in tt.get("values", []) for c in v.get("citations", [])]


def summary_table() -> str:
    tts = RESULT["term_types"]
    rows = []
    tot = collections.Counter()
    for key, label in CATS:
        sub = [t for t in tts if t["applies_to"] == key]
        n_vals = sum(len(t["values"]) for t in sub)
        cs = [c for t in sub for c in cites(t)]
        n_ok = sum(1 for c in cs if c.get("verified"))
        docs = sum(len(t["sources"]["documents"]) for t in sub)
        single = sum(1 for t in sub if len(t["sources"]["documents"]) == 1)
        notes = sum(1 for t in sub if t["notes"].strip())
        tot.update(types=len(sub), vals=n_vals, cites=len(cs), ok=n_ok, docs=docs, single=single, notes=notes)
        rows.append(f"    {label} & {len(sub)} & {n_vals} & {docs/len(sub):.1f} & {single} & {notes} & {len(cs)} & {100*n_ok/len(cs):.1f} \\\\")
    rows.append("    \\midrule")
    rows.append(f"    All & {tot['types']} & {tot['vals']} & {tot['docs']/tot['types']:.1f} & {tot['single']} & {tot['notes']} & {tot['cites']} & {100*tot['ok']/tot['cites']:.1f} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{@{}lrrrrrrr@{}}",
        "    \\toprule",
        "    Category & Types & Values & Docs & Single & Confl. & Cites & Verif.\\,\\% \\\\",
        "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


def corpus_table() -> str:
    tts = RESULT["term_types"]
    uses = collections.Counter(d for t in tts for d in t["sources"]["documents"])
    rows = []
    tot_sec = tot_words = 0
    for m in DOC_RE.finditer(CORPUS):
        i, meta, body = int(m.group(1)), m.group(2), m.group(3)
        jur = (re.search(r'jurisdiction="([^"]*)"', meta) or [None, ""])[1]
        secs = SEC_RE.findall(body)
        words = sum(len(s[1].split()) for s in secs)
        tot_sec += len(secs); tot_words += words
        rows.append(f"    {i} & {JUR[jur]} & {SHORT[i]} & {len(secs)} & {words/1000:.1f} & {uses[i]} \\\\")
    rows.append("    \\midrule")
    rows.append(f"    \\multicolumn{{3}}{{@{{}}l}}{{Total}} & {tot_sec} & {tot_words/1000:.1f} & {len(tts)} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{@{}rllrrr@{}}",
        "    \\toprule",
        "    \\# & Jur. & Source & Sect. & Words\\,(k) & Types \\\\",
        "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


if __name__ == "__main__":
    TABLES.mkdir(exist_ok=True)
    (TABLES / "task_a_summary.tex").write_text(summary_table())
    (TABLES / "corpus.tex").write_text(corpus_table())
    print("wrote", TABLES / "task_a_summary.tex", "and", TABLES / "corpus.tex")


