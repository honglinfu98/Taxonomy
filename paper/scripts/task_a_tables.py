def numbers() -> str:
    """\\newcommand macros for numbers quoted in the prose."""
    res = ISA["is_a"]
    n = ok = rel = 0
    for r in res:
        for e in r["distribution"]:
            for c in e["citations"]:
                n += 1; ok += bool(c.get("verified")); rel += "cited_section" in c
    entries = sum(len(r["distribution"]) for r in res)
    cited = sum(1 for r in res for e in r["distribution"] if e["citations"])
    top_nocite = sum(1 for r in res if r["distribution"] and not r["distribution"][0]["citations"])
    tops = sorted(r["distribution"][0]["probability"] for r in res if r["distribution"])
    median_top = tops[len(tops) // 2]
    P = {(r["child"], e["parent"]) for r in res for e in r["distribution"]}
    mutual = sum(1 for (c, q) in P if (q, c) in P and c < q)
    kept = [len(v["parents"]) for v in ISA["dag"]["nodes"].values()]
    m = DAG["metrics"]["overall"]
    run = ISA["run"]
    vals = {
        "nTermTypes": len(RESULT["term_types"]),
        "BEdges": m["edges"], "BRoots": m["roots"], "BLeaves": m["leaves"], "BDepth": m["max_depth"],
        "BBits": f"{m['information_gain']['bits_per_descent']:.2f}", "BAUC": f"{m['auc']['value']:.3f}",
        "BEDepth": f"{m['auc']['expected_depth']:.2f}", "BEffLeaves": f"{m['leaves_needed']['effective_leaves']:.1f}",
        "BWeighted": entries, "BDropped": len(DAG["dropped_for_cycle"]), "BTies": len(DAG["ties"]), "BMutual": mutual,
        "BCites": n, "BVerified": ok, "BRelabelled": rel, "BRejected": n - ok, "BVerifiedPct": f"{100 * ok / n:.1f}",
        "BEntriesCited": cited, "BTopNoCite": top_nocite, "BMedianTop": f"{median_top:.2f}",
        "BMeanParents": f"{sum(kept) / len(kept):.1f}", "BMaxParents": max(kept),
        "BSeconds": run["seconds"], "BCalls": run["children"], "BOutTokens": f"{run['usage']['output_tokens']:,}",
        "BInTokens": f"{run['usage']['input_tokens']:,}", "BCacheTokens": f"{run['usage']['cache_read_input_tokens'] / 1e6:.1f}",
    }
    return "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.\n" + "\n".join(
        f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in vals.items()) + "\n"


def tree_figure(cat: str) -> str:
    """Primary-parent tree of one category as a forest 'folder' tree (node label: name (w))."""
    nodes = ISA["dag"]["nodes"]
    by_id = {t["id"]: t for t in RESULT["term_types"]}
    ids = [r["child"] for r in ISA["is_a"] if r["category"] == cat]
    kids: dict[str, list[str]] = {}
    for c in ids:
        prim = nodes[c]["parents"][0][0] if nodes[c]["parents"] else "ROOT"
        kids.setdefault(prim, []).append(c)

    def label(c: str) -> str:
        ps = nodes[c]["parents"]
        extra = f", +{len(ps) - 1}" if len(ps) > 1 else ""
        w = f" ({ps[0][1]:.2f}{extra})" if ps else ""
        return "{" + tex(by_id[c]["name"]) + w + "}"

    def walk(c: str) -> str:
        ch = sorted(kids.get(c, []), key=lambda x: -(nodes[x]["parents"][0][1] if nodes[x]["parents"] else 1))
        return "[" + label(c) + "".join(walk(x) for x in ch) + "]"

    roots = kids.get("ROOT", [])
    body = "".join(walk(r) for r in roots)
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\begin{forest}",
        "  for tree={folder, grow'=0, font=\\scriptsize, inner sep=1.2pt, l sep=5pt, s sep=0.6pt,",
        "            edge={gray!70, thin}, draw=none, anchor=west, child anchor=west}",
        "  " + body,
        "\\end{forest}", ""])


