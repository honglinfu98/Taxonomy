def cites(tt: dict) -> list[dict]:
    return tt.get("citations", []) + [c for v in tt.get("values", []) for c in v.get("citations", [])]


def summary_table() -> str:
    tts = RESULT["term_types"]
    rows = []
    tot = collections.Counter()
    for key, label in CATS:
        sub = [t for t in tts if t["applies_to"] == key]
        n_vals = sum(len(t["values"]) for t in sub)
        cs = [c for t in sub for c in cites(t)]
        n_ok = sum(1 for c in cs if c.get("verified"))
        docs = sum(len(t["sources"]["documents"]) for t in sub)
        single = sum(1 for t in sub if len(t["sources"]["documents"]) == 1)
        notes = sum(1 for t in sub if t["notes"].strip())
        tot.update(types=len(sub), vals=n_vals, cites=len(cs), ok=n_ok, docs=docs, single=single, notes=notes)
        rows.append(f"    {label} & {len(sub)} & {n_vals} & {docs/len(sub):.1f} & {single} & {notes} & {len(cs)} & {100*n_ok/len(cs):.1f} \\\\")
    rows.append("    \\midrule")
    rows.append(f"    All & {tot['types']} & {tot['vals']} & {tot['docs']/tot['types']:.1f} & {tot['single']} & {tot['notes']} & {tot['cites']} & {100*tot['ok']/tot['cites']:.1f} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{@{}lrrrrrrr@{}}",
        "    \\toprule",
        "    Category & Types & Values & Docs & Single & Confl. & Cites & Verif.\\,\\% \\\\",
        "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


def corpus_table() -> str:
    tts = RESULT["term_types"]
    uses = collections.Counter(d for t in tts for d in t["sources"]["documents"])
    rows = []
    tot_sec = tot_words = 0
    for m in DOC_RE.finditer(CORPUS):
        i, meta, body = int(m.group(1)), m.group(2), m.group(3)
        jur = (re.search(r'jurisdiction="([^"]*)"', meta) or [None, ""])[1]
        secs = SEC_RE.findall(body)
        words = sum(len(s[1].split()) for s in secs)
        tot_sec += len(secs); tot_words += words
        rows.append(f"    {i} & {JUR[jur]} & {SHORT[i]} & {len(secs)} & {words/1000:.1f} & {uses[i]} \\\\")
    rows.append("    \\midrule")
    rows.append(f"    \\multicolumn{{3}}{{@{{}}l}}{{Total}} & {tot_sec} & {tot_words/1000:.1f} & {len(tts)} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{@{}rllrrr@{}}",
        "    \\toprule",
        "    \\# & Jur. & Source & Sect. & Words\\,(k) & Types \\\\",
        "    \\midrule", *rows, "    \\bottomrule", "\\end{tabular}", ""])


