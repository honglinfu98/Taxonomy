def tex(s: str) -> str:
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
             .replace("$", "\\$").replace("#", "\\#").replace("_", "\\_").replace("—", "--")
             .replace("‘", "`").replace("’", "'").replace("“", "``").replace("”", "''"))


def case_table(tt_id: str = "asset_reference_type") -> str:
    tt = next(t for t in RESULT["term_types"] if t["id"] == tt_id)
    rows = []
    for v in tt["values"]:
        c = v["citations"][0]
        rows.append(f"    {tex(v['value'])} & {tex(v['definition'])} & {SHORT[c['doc']]} \\\\")
    return "\n".join([
        "%% Generated by paper/scripts/task_a_tables.py -- do not edit by hand.",
        "\\begin{tabularx}{\\columnwidth}{@{}>{\\raggedright\\arraybackslash}p{0.22\\columnwidth}Xl@{}}",
        "    \\toprule", "    Value & Definition (model output) & Cited source \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "\\end{tabularx}", ""])


