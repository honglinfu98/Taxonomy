"""Exact billing figures from recorded API usage, priced at list rates.

    python -m taxonomy.evaluation.billing

Collects the usage recorded by every runner (Task A and its repeats, Task B, every tagging
iteration with discovery and consolidation, the gold annotation, the evaluation runs) and writes
output/evaluation/billing.{json,md} and paper/tables/billing.tex. Haiku 5.5 prompts over 100K
tokens (Task A, Task B) are priced at the long-prompt card ($0.50 / $2.50 per MTok, cache read
0.1x, 1-hour cache write 2x); everything else at the short card.
"""
from __future__ import annotations

import json
from pathlib import Path

from taxonomy.classification import catalogue as cat
from taxonomy.evaluation.common import OUT, PAPER_TABLES, PRICES
from taxonomy.llm_context import ROOT

EST = ROOT / "output" / "establishment"
HAIKU_LONG = {"input": 0.50e-6, "output": 2.50e-6, "cache_read": 0.05e-6, "cache_write": 1.0e-6}


def price(usage: dict, model: str, long_prompt: bool = False) -> float:
    p = HAIKU_LONG if (long_prompt and model.startswith("claude-haiku")) else PRICES.get(model, PRICES["claude-haiku-5-5"])
    if long_prompt and not model.startswith("claude-haiku"):
        p = dict(p)
        p["cache_write"] = p["input"] * 2          # 1-hour cache write is 2x input on every model
    u = {"input": usage.get("input", usage.get("input_tokens", 0)), "output": usage.get("output", usage.get("output_tokens", 0)),
         "cache_read": usage.get("cache_read", usage.get("cache_read_input_tokens", 0)) or 0,
         "cache_write": usage.get("cache_write", usage.get("cache_creation_input_tokens", 0)) or 0}
    return sum(u[k] * p[k] for k in p), u


def rows() -> list[dict]:
    out = []

    def add(stage, model, usage, secs, long_prompt=False, note=""):
        c, u = price(usage, model, long_prompt)
        out.append({"stage": stage, "model": model, "usd": round(c, 4), "seconds": secs, "tokens": u, "note": note})

    a = json.loads((EST / "term_types.json").read_text(encoding="utf-8"))["run"]
    add("Task A term types (run 1)", a["model"], a["usage"], a.get("seconds"), True, f"{a.get('effort')} effort, 1 streamed call")
    for p in sorted((EST / "repeats").glob("term_types.*.json")):
        if p.name.endswith(".verification.json") or p.name.endswith(".agreement.json"):
            continue
        r = json.loads(p.read_text(encoding="utf-8")).get("run", {})
        if r.get("usage"):
            add(f"Task A term types ({p.stem.split('.')[-1]})", r["model"], r["usage"], r.get("seconds"), True, "repeat")
    b = json.loads((EST / "is_a.json").read_text(encoding="utf-8"))["run"]
    add("Task B is-a distributions", b["model"], b["usage"], b.get("seconds"), True, f"{b.get('children')} calls")
    for e in cat.read_log():
        c = e["cost"]
        out.append({"stage": f"Iteration {e['iteration']}: tag {e['items']} items + discovery + consolidation", "model": "claude-haiku-5-5",
                    "usd": round(c["total_usd"], 4), "seconds": e["time"].get("wall_seconds"),
                    "tokens": {"input": c["input_tokens"], "output": c["output_tokens"], "cache_read": c["cache_read_tokens"], "cache_write": 0},
                    "note": f"tagging ${c['tagging_usd']}, discovery ${c['discovery_usd']}, consolidation ${c['evolve_usd']}"})
    g = OUT / "gold_summary.json"
    if g.exists():
        s = json.loads(g.read_text(encoding="utf-8"))
        add(f"Gold annotation: {s['items']} items x {s['passes']} passes", s["model"], s["usage"],
            sum(ps.get("wall_seconds", 0) for ps in s["pass_stats"]), False, f"{s.get('effort')} effort, adaptive thinking")
    t = OUT / "tagging_eval.json"
    if t.exists():
        te = json.loads(t.read_text(encoding="utf-8"))
        for sysname, runs in te["systems"].items():
            for r in runs:
                info = r["run_info"]
                if info.get("usage"):
                    add(f"Evaluation: {sysname} run {r['run']} ({te['gold']['items']} items)", info["model"], info["usage"], info.get("wall_seconds"))
    return out


def main() -> None:
    rs = rows()
    total = round(sum(r["usd"] for r in rs), 2)
    md = ["# Billing", "", "Usage recorded by each runner, priced at list rates (USD). Haiku 5.5 long-prompt card for Task A and Task B.", "",
          "| stage | model | input | cache read | cache write | output | USD | seconds | note |", "|---|---|---|---|---|---|---|---|---|"]
    tex = ["% generated by taxonomy.evaluation.billing", "\\begin{tabular}{llrrrr}", "\\toprule", "Stage & Model & Input (K) & Cached (M) & Output (K) & USD \\\\", "\\midrule"]
    for r in rs:
        t = r["tokens"]
        md.append(f"| {r['stage']} | {r['model']} | {t['input']:,} | {t['cache_read']:,} | {t['cache_write']:,} | {t['output']:,} | {r['usd']:.2f} | {r['seconds']} | {r['note']} |")
        tex.append(f"{r['stage']} & {r['model'].replace('claude-', '')} & {t['input'] / 1e3:.0f} & {t['cache_read'] / 1e6:.1f} & {t['output'] / 1e3:.0f} & {r['usd']:.2f} \\\\")
    md += ["", f"**Total: ${total}**"]
    tex += ["\\midrule", f"Total & & & & & {total:.2f} \\\\", "\\bottomrule", "\\end{tabular}"]
    (OUT / "billing.json").write_text(json.dumps({"rows": rs, "total_usd": total}, indent=1), encoding="utf-8")
    (OUT / "billing.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    PAPER_TABLES.mkdir(parents=True, exist_ok=True)
    (PAPER_TABLES / "billing.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
